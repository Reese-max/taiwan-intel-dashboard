import { spawnSync } from "node:child_process";
import { cpSync, mkdirSync, mkdtempSync, readFileSync, rmSync, symlinkSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";
import { pathToFileURL } from "node:url";
import { expect, it } from "vitest";
import { fingerprintEvent } from "../scripts/lib/curation-ledger.mjs";
import { RULES_VERSION } from "../scripts/lib/manifest.mjs";

it("persists reviewed decisions through complete repeat builds and reports changed evidence/conflicts", () => {
  const root = mkdtempSync(join(tmpdir(), "curation-rebuild-"));
  try {
    for (const folder of ["scripts", "src", "static"]) cpSync(folder, join(root, folder), { recursive: true });
    symlinkSync(resolve("node_modules"), join(root, "node_modules"), "junction");
    const data = join(root, "public/data");
    mkdirSync(data, { recursive: true });
    mkdirSync(join(root, "docs/curation"), { recursive: true });
    const events = JSON.parse(readFileSync("tests/fixtures/curation-events.json", "utf8"));
    events.push(...["a", "b"].map((part, index) => ({
      id: `twnews-forced-${part}`, title: `Synthetic unrelated ${part}`, summary: "Synthetic fixture",
      region: index === 0 ? "臺北市" : "高雄市", scope: "domestic", category: "其他", riskLevel: "low",
      timestamp: "2026-10-01T00:00:00Z", source: { name: `Synthetic ${part}`, type: "news-rss" },
    })));
    const byId = new Map(events.map((event: any) => [event.id, event]));
    const base = { schemaVersion: 1, reviewedAt: "2026-10-13T00:00:00Z", rulesVersion: RULES_VERSION,
      reason: "Synthetic reviewed correction", evidence: "https://example.invalid/review" };
    const record = (id: string, decision: string, subjects: string[], extra = {}) => ({
      ...base, id, decision, subjects,
      expect: Object.fromEntries(subjects.map((subject) => [subject, fingerprintEvent(byId.get(subject))])), ...extra,
    });
    const records = [
      record("not-same", "not_same_event", ["twnews-fixture-auto-a", "twnews-fixture-auto-b"]),
      record("forced", "same_event", ["twnews-forced-a", "twnews-forced-b"]),
      record("follow", "follow_up", ["twnews-fixture-sep-a", "twnews-fixture-sep-b"]),
      record("location", "location_correction", ["twnews-fixture-geo"], { patch: { locationRole: "agency" } }),
    ];
    const ledgerPath = join(root, "docs/curation/correlation-overrides.jsonl");
    const source = JSON.stringify(events);
    const ledger = records.map((entry) => JSON.stringify(entry)).join("\n");
    writeFileSync(join(data, "domestic.json"), source);
    writeFileSync(join(data, "international.json"), "[]");
    writeFileSync(join(data, "summary.json"), "{}");
    writeFileSync(ledgerPath, ledger);
    // The snapshot's declared clock is fixed so complete generated bytes can be compared.
    const clock = join(root, "fixture-clock.mjs");
    writeFileSync(clock, `const OriginalDate = Date; const stamp = OriginalDate.parse("2026-10-13T00:00:00Z");
globalThis.Date = class extends OriginalDate { constructor(...args) { super(...(args.length ? args : [stamp])); } static now() { return stamp; } };`);
    const run = (script: string) => {
      const result = spawnSync(process.execPath, ["--import", pathToFileURL(clock).href, join(root, "scripts", script)], {
        cwd: root, encoding: "utf8", env: { ...process.env, BUILD_DATA_DIR: data, BUILD_SYNTHETIC_INPUT: "1" },
      });
      expect(result.status, result.stderr).toBe(0);
    };
    const rebuild = () => { run("build-network.mjs"); run("build-static.mjs"); };
    rebuild();
    const first = readFileSync(join(root, "dist/data/network.json"), "utf8");
    const network = JSON.parse(first).domestic;
    expect(network.curation.applied).toBe(4);
    expect(network.edges.some((edge: any) => [edge.a, edge.b].includes("twnews-fixture-auto-a") && [edge.a, edge.b].includes("twnews-fixture-auto-b"))).toBe(false);
    expect(network.clusters.some((cluster: any) => cluster.members.includes("twnews-fixture-auto-a") && cluster.members.includes("twnews-fixture-auto-b"))).toBe(false);
    expect(network.edges).toContainEqual(expect.objectContaining({ origin: "manual", curationId: "forced", type: "same-incident" }));
    expect(network.edges).toContainEqual(expect.objectContaining({ origin: "manual", curationId: "follow", type: "follow-up" }));
    const built = JSON.parse(readFileSync(join(root, "dist/data/domestic.json"), "utf8"));
    expect(built.find((event: any) => event.id === "twnews-fixture-geo").locationRole).toBe("agency");
    expect(readFileSync(join(data, "domestic.json"), "utf8")).toBe(source);
    expect(readFileSync(ledgerPath, "utf8")).toBe(ledger);
    rebuild();
    expect(readFileSync(join(root, "dist/data/network.json"), "utf8")).toBe(first);
    const changed = JSON.parse(source);
    changed[0].summary = "Changed synthetic source evidence";
    writeFileSync(join(data, "domestic.json"), JSON.stringify(changed));
    rebuild();
    const stale = JSON.parse(readFileSync(join(root, "dist/data/network.json"), "utf8")).domestic;
    expect(stale.curation.decisions.find((entry: any) => entry.id === "not-same")).toMatchObject({ status: "needs_review", note: "fingerprint_mismatch" });
    writeFileSync(join(data, "domestic.json"), source);
    writeFileSync(ledgerPath, `${ledger}\n${JSON.stringify(record("contradiction", "same_event", records[0].subjects))}`);
    rebuild();
    const conflict = JSON.parse(readFileSync(join(root, "dist/data/network.json"), "utf8")).domestic;
    expect(conflict.curation.decisions.filter((entry: any) => entry.status === "conflict").map((entry: any) => entry.id)).toEqual(["not-same", "contradiction"]);
    expect(conflict.edges.some((edge: any) => edge.curationId === "contradiction")).toBe(false);
    expect(readFileSync(join(data, "domestic.json"), "utf8")).toBe(source);
  } finally {
    rmSync(root, { recursive: true, force: true });
  }
});
